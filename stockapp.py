import numpy as np
import os
from dotenv import load_dotenv
from groq import Groq

# PDF + Charts
import matplotlib.pyplot as plt
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Image, Spacer, Table, TableStyle
)
